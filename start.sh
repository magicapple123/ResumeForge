#!/bin/bash
# 简历通（ResumeForge）Linux 启动入口。
#
# 用法（任选其一）：
#   1) 终端里：bash start.sh
#   2) 文件管理器里右键 → 「在终端中运行」/ 双击（取决于桌面环境与文件管理器设置）
#   3) 想在应用菜单/桌面放一个图标时，Exec 指向这个文件的绝对路径即可
#
# 这一层只做三件事：切到脚本自己所在的目录、把参数原样交给真正的启动器、
# 失败时停住窗口。加这一层的理由与 macOS 的 start.command 相同：用户很可能从
# 任意目录、或通过图形入口（工作目录不确定）启动，而启动器内部大量路径是相对
# 项目根的。切到自身目录之后，"从哪里启动"就与成败无关了。
#
# 真正的实现在 scripts/linux/start.sh（可读性考虑：入口薄、实现厚）。

cd "$(dirname "${BASH_SOURCE[0]:-$0}")" || exit 1

bash "scripts/linux/start.sh" "$@"
status=$?

# 失败时停住：从图形入口启动时，终端窗口会在脚本退出后立刻关闭，用户根本来不及
# 看到报错。成功时不拦——成功的信息用户不需要抄下来。
if [ "$status" -ne 0 ]; then
    printf '\n按回车键关闭这个窗口。\n'
    read -r _
fi
exit "$status"
