"""助手"何时建任务"的提示词块（18A）。

单独成模块而不是直接塞进 assistant_system.md 的原因：这段规则同时服务两件事——
① 装配进系统提示（由 assistant_system_prompt.py 拼一段，改动交主 agent 合并）；
② 评测护栏（tests/test_assistant_eval.py 按同一份文字的要点断言，不许提示词被悄悄删掉）。

规则本身来自问题清单 #18A：
- 一次性、一轮内能完成 → **直接做**，不要为了"显得有条理"建任务；
- 需要 >20 次工具调用（跨轮批量）→ 建任务卡；
- 只改一个字段 / 只建一条记录 / 只回答一个问题 → **不得**建任务（反例：每个小需求都
  变成后台任务，用户会在任务堆里找不到真正要等的那张卡）。
"""

from __future__ import annotations

TASK_RULES_BLOCK = """【长任务：什么时候建任务卡，什么时候直接做】
- 一轮内能做完的，直接做完再回答；不要为了"看起来有条理"建任务。
- 只有**跨轮批量、预计工具调用超过 20 次**的活才用 task_create 建任务卡（批量改写多条简历内容、
  从链接导入多页岗位、批量匹配、批量生成打招呼语）。
- **只改一个字段、只建一条记录、只回答一个问题，不得建任务**——那会把小需求也变成后台任务。
- 建任务前先把 N 算准：先用 list_resumes / list_jobs / get_resume 查真实条数，算不出来就先问用户，
  不要报一个估计数字。提案卡上会写明"将处理 N 条、预计 M 步"，用户会逐条核对。
- 任务建好后不要在同一轮里自己反复推进它；告诉用户去任务卡开始/暂停/取消，要查进度用 task_status。
- 用户说"继续"是接着上一轮没说完整的回答（输入框上方的继续按钮）；任务卡上的"继续"是另一回事，
  不要把两者混为一谈。"""


def build_task_rules_block() -> str:
    """返回注入系统提示的长任务规则块（恒定文本，不做条件拼接）。"""
    return TASK_RULES_BLOCK


__all__ = ["TASK_RULES_BLOCK", "build_task_rules_block"]
