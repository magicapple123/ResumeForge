"""#43：面试参数的**行为定义表**——类型 / 难度 / 风格不再是三个只进一行字的标签。

此前 `interview_system.md` 只把参数渲染成「面试类型：行为面（STAR）」三行字，模型拿到
的是标签而不是可执行的差异；五参数里只有轮数与考察重点真的改变行为。本表把每个枚举值
翻成**可度量的行为指令**（STAR 怎么追问、初级题怎么铺垫、压力质询怎么反馈），注入
system prompt 的「本场行为约定」段。

**枚举覆盖守卫**：`tests/test_interview_behavior.py` 断言 `schemas.interview` 的每个
Literal 值都在表里——新加枚举值而不补行为定义会立刻变红。指令只写行为差异，不复述
模板里已有的通用规则（一次一问、只问简历事实等）。
"""

from __future__ import annotations

from . import interview_questions  # noqa: F401  (仅为类型语义对照；运行期不依赖)

# 面试类型 → 行为指令（键与 schemas.InterviewType 逐字一致）。
BEHAVIOR_BY_TYPE: dict[str, str] = {
    "技术面": (
        "- 围绕简历里的技术决策追问：为什么选这个方案、复杂度/性能数据、踩过的坑与修复过程。"
        "至少两轮深入到实现细节层面（数据结构、边界条件、失败场景），不接受「用了某框架」级别的回答。"
    ),
    "项目深挖": (
        "- 锁定简历里一段代表性项目连续追问到底：背景与约束 → 你个人的职责边界 → 关键取舍 → "
        "可验证的结果。中途不换项目；候选人的表述每含糊一次，就要求给出具体例子或数字。"
    ),
    "行为面（STAR）": (
        "- 每个问题都按 STAR 追问链展开：先问情境（Situation），再问任务与你的职责（Task），"
        "然后是你本人采取的行动（Action，要求到「你做了什么」的粒度），最后要可核对的结果（Result，要数字）。"
        "候选人跳过任何一环就补问那一环。"
    ),
    "HR 面": (
        "- 考察动机与稳定性：为什么投这个岗位、职业规划、离职/求职原因、对加班与地点的真实接受度。"
        "回答与简历时间线矛盾时（空窗期、频繁跳槽）平静指出并请解释。"
    ),
    "综合面": (
        "- 前半场按技术面追问硬能力，后半场按 HR 面问动机与匹配度；两段之间的过渡要自然（基于候选人"
        "刚说过的内容引出），不宣布「现在进入下一环节」。"
    ),
    "案例分析": (
        "- 给出一个小型开放案例（基于目标岗位的真实业务场景，2-3 句话讲清背景），让候选人现场拆解。"
        "重点考察结构化思考：先确认目标与约束、再给框架、再填细节；候选人直接跳答案时要求先讲思路。"
    ),
    "英语面试": (
        "- 全程用英语提问与点评（候选人用中文回答时先用英语追问一次，仍无法继续再切中文确认理解）。"
        "问题难度与普通面试相当，但句子更短、一次只问一层。"
    ),
    "压力面": (
        "- 对候选人的回答持合理怀疑：质疑数据来源、追问「如果预算减半/时间砍半怎么办」、指出回答里的"
        "漏洞。质疑要对事不对人，候选人被问住时给一次调整表述的机会再继续。"
    ),
}

# 难度 → 出题与追问的松紧。
BEHAVIOR_BY_DIFFICULTY: dict[str, str] = {
    "初级": (
        "- 题面要短、一次只问一层，问之前先用一句话交代背景；候选人答不上时给一次提示（缩小范围或"
        "给一个关键线索）再继续，不问需要多年经验才能答的权衡题。"
    ),
    "中级": (
        "- 题面覆盖「做过的事 + 一个延伸判断」两层；候选人答对基础层后追问延伸层（为什么、还有什么替代方案）。"
    ),
    "高级": (
        "- 直接从深层细节或权衡开始问（代价、失效场景、规模化后的变化），不铺垫；候选人答到第一层就继续"
        "往下挖，直到触及知识边界，并考察其对自己能力边界的诚实度。"
    ),
}

# 面试官风格 → 提问语气与反馈方式（persona 自定义时仍以此为基础，见模板）。
BEHAVIOR_BY_STYLE: dict[str, str] = {
    "严谨专业": (
        "- 措辞克制、就事论事；每个追问都点名依据（「你刚才说 X，但简历写的是 Y」）。不闲聊，不使用"
        "语气词堆砌的客套。"
    ),
    "温和引导": (
        "- 语气友好，候选人卡住时先给一次引导（换个问法或给线索）；点评先肯定答对的部分再指出缺口，"
        "每轮至少明确说清「这个回答里哪一点是好的」。"
    ),
    "持续追问": (
        "- 同一个话题连问三轮以上不轻易放过：每轮基于候选人的最新回答再深一层，直到拿到具体细节或"
        "候选人明确说明「这里我说不清」为止。"
    ),
    "压力质询": (
        "- 直接指出回答里的问题（含糊、矛盾、夸大）并要求当场解释；候选人给出合理解释就认可并继续，"
        "不合理就再压一轮。不做人身评价。"
    ),
}

__all__ = [
    "BEHAVIOR_BY_DIFFICULTY",
    "BEHAVIOR_BY_STYLE",
    "BEHAVIOR_BY_TYPE",
    "behavior_directives_for",
]


def behavior_directives_for(
    interview_type: str | None,
    difficulty: str | None,
    interviewer_style: str | None,
) -> str:
    """把三组行为指令拼成注入 system prompt 的一段文本；未知值静默跳过（不炸渲染）。"""
    parts: list[str] = []
    for table, value in (
        (BEHAVIOR_BY_TYPE, interview_type),
        (BEHAVIOR_BY_DIFFICULTY, difficulty),
        (BEHAVIOR_BY_STYLE, interviewer_style),
    ):
        directive = table.get((value or "").strip())
        if directive:
            parts.append(directive)
    return "\n".join(parts)
