/**
 * 「生成简历」目录里与**当前组**有关的板块范围（4-A）。
 *
 * 为什么单独一个文件：`resume.ts` 贴着 500 行预算（`test_file_size_budget`），这套契约又
 * 需要写清"为什么不能直接裁剪 `section_options`"这类容易被下一个人改错的口径。拆出来与
 * `resumeContent.ts` 同一个理由：让口径有地方写，而不是把文件顶破预算。
 *
 * 背景（用户反馈）：为某个岗位生成简历时，顶部摘要写「本次使用：我是测试（6 个板块）」，
 * 但「调整板块顺序」列出了 11 个系统板块，被当前组隐藏的板块还能被排到最前面。根因是
 * 可排序清单取自**静态目录**（`section_options`：11 个系统键全量 + 全局自建板块），
 * 而"当前组参与哪些板块"这个局部约束从未与它相交。
 *
 * 为什么**不直接**按组裁剪 `section_options`：那份清单是全局目录，
 * `features/career-scenarios/ScenarioEditor.tsx` 也在用它，而场景编辑与"当前组"无关。
 * 所以范围单独下发两个字段，由生成弹窗自己决定要不要用。
 */
export interface GroupSectionScope {
  /**
   * 当前组参与的分区，已映射成简历正文分区键（`custom:<key>` 原样透传，页眉 `basic_info` 除外）。
   *
   * 只用于**过滤**「调整板块顺序」的可选项，与顺序无关。**空数组或缺省 = 读不到当前组**
   * （组为空 / 组里只有页眉 / 投影读取失败 / 旧后端没有这个字段）：调用方必须回退到全量
   * 清单——绝不能据此显示空列表，否则「调整板块顺序」会整块消失，用户什么都排不了。
   */
  group_section_keys?: string[];
  /**
   * 同一份组范围清单的**顺序**形态：生成时的默认板块顺序与「与资料顺序同步」都读它。
   *
   * 因此同步写回的 `section_order` 只会含当前组参与的键，不会把被隐藏的板块写回去
   * （那些板块的内容本来就不会参与这次生成）。缺省时回退 `profile_section_order`（旧行为）。
   */
  group_section_order?: string[];
}
