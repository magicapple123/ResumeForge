<#
.SYNOPSIS
    Generate the third-party notices and a frozen dependency list for releases (RF-24).

.DESCRIPTION
    Runs pip-licenses against the backend environment and writes:
      - THIRD-PARTY-NOTICES.txt : package / version / license table (markdown)
      - requirements-frozen.txt : the resolved dependency set of that environment

    Both files are release artifacts; the CI dependency-audit job uploads them
    alongside the audit results. This script intentionally stays separate from
    Build-Release.ps1 so the packaging script keeps a single responsibility.

.PARAMETER Python
    Path to the Python interpreter whose environment should be inventoried.
    Defaults to backend\.venv\Scripts\python.exe when present, else "python".

.PARAMETER OutputDir
    Directory that receives the two files. Defaults to <repo>\runtime\sbom.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File scripts\Generate-Sbom.ps1
#>
[CmdletBinding()]
param(
    [string]$Python,
    [string]$OutputDir
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $Python) {
    if ($IsWindows -or $env:OS -eq "Windows_NT") {
        $venvPython = Join-Path $repoRoot "backend\.venv\Scripts\python.exe"
    } else {
        $venvPython = Join-Path $repoRoot "backend/.venv/bin/python"
    }
    if (Test-Path $venvPython) {
        $Python = $venvPython
    } else {
        $cmd = Get-Command python -ErrorAction SilentlyContinue
        if (-not $cmd) { $cmd = Get-Command python3 -ErrorAction SilentlyContinue }
        if (-not $cmd) { throw "Python interpreter not found (tried venv, python, python3)" }
        $Python = $cmd.Source
    }
}
if (-not $OutputDir) {
    $OutputDir = Join-Path $repoRoot "runtime\sbom"
}

if (-not (Test-Path $Python)) {
    throw "Python interpreter not found: $Python"
}

New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null
$noticesPath = Join-Path $OutputDir "THIRD-PARTY-NOTICES.txt"
$frozenPath = Join-Path $OutputDir "requirements-frozen.txt"

Write-Host "Using Python: $Python"
& $Python -m piplicenses --version
if ($LASTEXITCODE -ne 0) {
    throw "pip-licenses is not installed in this environment (pip install pip-licenses)."
}

# License inventory: "mixed" reads package metadata first and falls back to
# classifier-derived licenses, which keeps entries for wheels that ship no
# LICENSE field. Output is a markdown table, which reads fine as .txt.
& $Python -m piplicenses `
    --from=mixed `
    --format=markdown `
    --output-file $noticesPath
if ($LASTEXITCODE -ne 0) {
    throw "pip-licenses failed with exit code $LASTEXITCODE."
}

# 产物的字节必须与 CI 一致。两个平台各有自己的默认值：Windows PowerShell 5.1
# 的 Set-Content -Encoding UTF8 会写 BOM，Windows 上 Python 写 CRLF，CI 的
# Ubuntu + pwsh 7 则都是无 BOM 的 LF。任其自然就会让"本地重跑"产出一份只差
# 编码的空差异，所以这里统一按 CI 的形态写：UTF-8 无 BOM + LF。
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

# A short header so the file is self-explanatory years from now.
$notices = (Get-Content -Raw $noticesPath) -replace "`r`n", "`n"
$header = @(
    "ResumeForge third-party package notices",
    "Generated by scripts/Generate-Sbom.ps1 on $(Get-Date -Format 'yyyy-MM-dd').",
    "Licenses are read from the installed distributions' own metadata;",
    "they describe the upstream packages, not this repository.",
    ""
) -join "`n"
[System.IO.File]::WriteAllText($noticesPath, $header + $notices, $utf8NoBom)

# Frozen list of the inventoried environment. 同样是 LF + 无 BOM：包名与版本号
# 全是 ASCII，所以字节与原来的 -Encoding ASCII 输出完全一致，只是行尾统一了。
$frozen = (& $Python -m pip freeze --exclude-editable) -join "`n"
if ($LASTEXITCODE -ne 0) {
    throw "pip freeze failed with exit code $LASTEXITCODE."
}
[System.IO.File]::WriteAllText($frozenPath, $frozen + "`n", $utf8NoBom)

Write-Host "Written: $noticesPath"
Write-Host "Written: $frozenPath"
